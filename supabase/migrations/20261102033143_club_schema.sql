 select b.*,c.full_name as customer_name,s.name as station_name,t.name as tariff_name from public.bookings b
 join public.customers c on c.id=b.customer_id join public.stations s on s.id=b.station_id join public.tariffs t on t.id=b.tariff_id;
create view public.sessions_list with (security_invoker=true) as
 select x.*,b.station_id,b.customer_id,s.name as station_name,c.full_name as customer_name from public.sessions x
 join public.bookings b on b.id=x.booking_id join public.stations s on s.id=b.station_id join public.customers c on c.id=b.customer_id;
create view public.payments_list with (security_invoker=true) as
 select p.*,c.full_name as customer_name,s.name as station_name from public.payments p join public.bookings b on b.id=p.booking_id
 join public.customers c on c.id=b.customer_id join public.stations s on s.id=b.station_id;
