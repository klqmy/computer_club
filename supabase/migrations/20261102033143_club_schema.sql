begin;
create extension if not exists btree_gist with schema extensions;
create schema if not exists private;
revoke all on schema private from public, anon;
grant usage on schema private to authenticated;

create table public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 full_name text not null, role text not null default 'client' check(role in ('admin','operator','client')),
 active boolean not null default true, created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(), deleted_at timestamptz
);
create table public.customers (
 id bigint generated by default as identity primary key,
 profile_id uuid unique references public.profiles(id) on delete restrict,
 full_name text not null, email text not null, phone text not null,
 birth_year int not null, category text not null default 'guest',
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), deleted_at timestamptz
);
create unique index customers_email_unique on public.customers(lower(email));
create table public.zones (
 id bigint generated by default as identity primary key, name text not null unique,
 kind text not null, description text, seat_limit int not null, active boolean not null default true,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), deleted_at timestamptz
);
create table public.stations (
 id bigint generated by default as identity primary key, zone_id bigint not null references public.zones(id),
 name text not null unique, cpu text not null, gpu text not null, ram_gb int not null,
 state text not null default 'ready', notes text,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), deleted_at timestamptz
);
create table public.games (
 id bigint generated by default as identity primary key, title text not null unique,
 genre text not null, age_rating text not null, mode text not null, size_gb numeric(7,2) not null,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), deleted_at timestamptz
);
create table public.station_games (
 id bigint generated by default as identity primary key,
 station_id bigint not null references public.stations(id), game_id bigint not null references public.games(id),
 version text not null, installed_at date not null default current_date, enabled boolean not null default true,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), deleted_at timestamptz,
 unique(station_id,game_id)
);
create table public.tariffs (
 id bigint generated by default as identity primary key, zone_id bigint not null references public.zones(id),
 name text not null unique, price_per_hour numeric(9,2) not null, min_minutes int not null,
 step_minutes int not null, night_discount_percent int not null default 0, active boolean not null default true,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), deleted_at timestamptz
);
create table public.memberships (
 id bigint generated by default as identity primary key,
 customer_id bigint not null unique references public.customers(id), card_number text not null unique,
 level text not null, discount_percent int not null default 0, issued_at date not null, valid_until date not null,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), deleted_at timestamptz
);
create table public.bookings (
 id bigint generated by default as identity primary key,
 customer_id bigint not null references public.customers(id), station_id bigint not null references public.stations(id),
 tariff_id bigint not null references public.tariffs(id), starts_at timestamptz not null, ends_at timestamptz not null,
 status text not null default 'reserved', quoted_total numeric(10,2) not null default 0,
 billable_minutes int not null default 0, discount_percent int not null default 0,
 night_discount_percent int not null default 0, comment text,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), deleted_at timestamptz,
 constraint bookings_valid_interval check(ends_at > starts_at),
 constraint bookings_no_overlap exclude using gist
 (station_id with =, tstzrange(starts_at,ends_at,'[)') with &&)
 where (deleted_at is null and status <> 'cancelled')
);
create table public.sessions (
 id bigint generated by default as identity primary key,
 booking_id bigint not null unique references public.bookings(id), operator_id uuid not null references public.profiles(id),
 started_at timestamptz not null, finished_at timestamptz, actual_minutes int not null default 0,
 charge numeric(10,2) not null default 0, notes text,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), deleted_at timestamptz
);
create table public.payments (
 id bigint generated by default as identity primary key, booking_id bigint not null references public.bookings(id),
 operator_id uuid not null references public.profiles(id), amount numeric(10,2) not null,
 method text not null, state text not null default 'received', paid_at timestamptz not null default now(),
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), deleted_at timestamptz
);

-- No role comes from user-editable auth metadata or browser storage.
create function private.current_role() returns text language sql stable security definer
 set search_path = '' as $$
 select role from public.profiles where id = (select auth.uid()) and active and deleted_at is null
$$;
create function private.customer_id() returns bigint language sql stable security definer
 set search_path = '' as $$
 select c.id from public.customers c join public.profiles p on p.id=c.profile_id
 where p.id=(select auth.uid()) and p.active and p.deleted_at is null and c.deleted_at is null
$$;
revoke all on function private.current_role(),private.customer_id() from public, anon;
grant execute on function private.current_role(),private.customer_id() to authenticated;

-- A compact rule registry is used only by the validation trigger, never exposed by REST.
create function private.field_rules(table_name text) returns jsonb language sql immutable set search_path='' as $$
select case table_name
when 'profiles' then '{"full_name":{"required":true,"length":100},"role":{"enum":["admin","operator","client"]}}'
when 'customers' then '{"full_name":{"required":true,"length":100},"email":{"required":true,"length":120,"pattern":"^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$"},"phone":{"required":true,"pattern":"^[+]?[0-9 ()-]{10,20}$"},"birth_year":{"required":true,"min":1920,"max":2026},"category":{"enum":["regular","student","guest"]}}'
when 'zones' then '{"name":{"required":true,"length":60},"kind":{"enum":["standard","vip","console"]},"description":{"length":400},"seat_limit":{"required":true,"min":1,"max":100},"active":{"required":true}}'
when 'stations' then '{"name":{"required":true,"length":40},"zone_id":{"required":true,"ref":"zones"},"cpu":{"required":true,"length":100},"gpu":{"required":true,"length":100},"ram_gb":{"required":true,"min":4,"max":256},"state":{"enum":["ready","maintenance","offline"]},"notes":{"length":400}}'
when 'games' then '{"title":{"required":true,"length":100},"genre":{"required":true,"length":50},"age_rating":{"enum":["0","6","12","16","18"]},"mode":{"enum":["single","multi","both"]},"size_gb":{"required":true,"min":0.1,"max":1000}}'
when 'station_games' then '{"station_id":{"required":true,"ref":"stations"},"game_id":{"required":true,"ref":"games"},"version":{"required":true,"length":30},"installed_at":{"required":true},"enabled":{"required":true}}'
when 'tariffs' then '{"name":{"required":true,"length":60},"zone_id":{"required":true,"ref":"zones"},"price_per_hour":{"required":true,"min":1,"max":10000},"min_minutes":{"required":true,"min":15,"max":720},"step_minutes":{"required":true,"min":1,"max":60},"night_discount_percent":{"required":true,"min":0,"max":50},"active":{"required":true}}'
when 'memberships' then '{"customer_id":{"required":true,"ref":"customers"},"card_number":{"required":true,"pattern":"^PC-[0-9]{6}$"},"level":{"enum":["base","silver","gold"]},"discount_percent":{"required":true,"min":0,"max":30},"issued_at":{"required":true},"valid_until":{"required":true}}'
when 'bookings' then '{"customer_id":{"required":true,"ref":"customers"},"station_id":{"required":true,"ref":"stations"},"tariff_id":{"required":true,"ref":"tariffs"},"starts_at":{"required":true},"ends_at":{"required":true},"status":{"enum":["reserved","checked_in","completed","cancelled"]},"comment":{"length":400}}'
when 'sessions' then '{"booking_id":{"required":true,"ref":"bookings"},"started_at":{"required":true},"notes":{"length":400}}'
when 'payments' then '{"booking_id":{"required":true,"ref":"bookings"},"amount":{"required":true,"min":0.01,"max":100000},"method":{"enum":["cash","card"]},"state":{"enum":["received","refunded"]},"paid_at":{"required":true}}'
else '{}' end::jsonb
$$;
create function private.validate_row() returns trigger language plpgsql set search_path='' as $$
declare r jsonb:=to_jsonb(new); errors jsonb:='{}'; f text; rule jsonb; v text; exists_ref boolean;
begin
 for f,rule in select * from jsonb_each(private.field_rules(tg_table_name)) loop
  v:=r->>f;
  if (rule->>'required')::boolean and (v is null or btrim(v)='') then
   errors:=errors||jsonb_build_object(f,'Заполните поле');
  elsif v is not null and btrim(v)<>'' then
   if rule ? 'length' and char_length(v)>(rule->>'length')::int then errors:=errors||jsonb_build_object(f,'Слишком длинное значение'); end if;
   if rule ? 'pattern' and v !~ (rule->>'pattern') then errors:=errors||jsonb_build_object(f,'Неверный формат'); end if;
   if rule ? 'min' and v::numeric<(rule->>'min')::numeric then errors:=errors||jsonb_build_object(f,'Значение меньше допустимого'); end if;
   if rule ? 'max' and v::numeric>(rule->>'max')::numeric then errors:=errors||jsonb_build_object(f,'Значение больше допустимого'); end if;
   if rule ? 'ref' then
    execute format('select exists(select 1 from public.%I where id=$1 and deleted_at is null)',rule->>'ref') into exists_ref using v::bigint;
    if not exists_ref then errors:=errors||jsonb_build_object(f,'Связанная запись недоступна или удалена'); end if;
   end if;
  end if;
  if rule ? 'enum' and (v is null or not (rule->'enum' ? v)) then errors:=errors||jsonb_build_object(f,'Выберите допустимое значение'); end if;
 end loop;
 if tg_table_name='memberships' then
  if new.valid_until<new.issued_at then errors:=errors||'{"valid_until":"Дата окончания раньше даты выдачи"}'; end if;
 end if;
 if errors<>'{}'::jsonb then raise sqlstate 'PT422' using message='Проверьте поля формы', detail=errors::text; end if;
 new.updated_at:=now();
 return new;
end $$;
revoke all on function private.field_rules(text),private.validate_row() from public, anon;
grant execute on function private.field_rules(text) to authenticated;

create function public.quote_booking(p_customer_id bigint,p_station_id bigint,p_tariff_id bigint,p_starts_at timestamptz,p_ends_at timestamptz)
returns jsonb language plpgsql stable security invoker set search_path='' as $$
declare t public.tariffs; s public.stations; minutes int; billable int; discount int:=0; night_discount int:=0;
 a timestamp; b timestamp; night_start timestamp; total numeric; role_name text:=private.current_role();
begin
 if role_name is null or (role_name='client' and p_customer_id is distinct from private.customer_id()) then raise insufficient_privilege using message='Доступ запрещён'; end if;
 if p_starts_at is null or p_ends_at is null or p_ends_at<=p_starts_at or extract(epoch from p_ends_at-p_starts_at)/60 not between 15 and 720 then
  raise sqlstate 'PT422' using message='Недопустимый интервал',detail='{"ends_at":"Продолжительность от 15 минут до 12 часов"}'; end if;
 select * into s from public.stations where id=p_station_id and deleted_at is null;
 select * into t from public.tariffs where id=p_tariff_id and deleted_at is null and active;
 if s.id is null or s.state<>'ready' then raise sqlstate 'PT422' using message='Компьютер недоступен',detail='{"station_id":"Выберите доступный компьютер"}'; end if;
 if t.id is null or t.zone_id<>s.zone_id or not exists(select 1 from public.zones where id=s.zone_id and active and deleted_at is null) then
  raise sqlstate 'PT422' using message='Тариф недоступен',detail='{"tariff_id":"Тариф должен соответствовать активной зоне компьютера"}'; end if;
 if not exists(select 1 from public.customers where id=p_customer_id and deleted_at is null) then
  raise sqlstate 'PT422' using message='Клиент недоступен',detail='{"customer_id":"Выберите действующего клиента"}'; end if;
 minutes:=ceil(extract(epoch from p_ends_at-p_starts_at)/60);
 billable:=ceil(greatest(minutes,t.min_minutes)::numeric/t.step_minutes)*t.step_minutes;
 select m.discount_percent into discount from public.memberships m where m.customer_id=p_customer_id and m.deleted_at is null
  and (p_starts_at at time zone 'Europe/Moscow')::date>=m.issued_at
  and (p_ends_at at time zone 'Europe/Moscow')::date<=m.valid_until;
 discount:=coalesce(discount,0);
 a:=p_starts_at at time zone 'Europe/Moscow'; b:=p_ends_at at time zone 'Europe/Moscow';
 night_start:=date_trunc('day',a)+interval '22 hours';
 if a::time<time '08:00' then night_start:=night_start-interval '1 day'; end if;
 if a>=night_start and b<=night_start+interval '10 hours' then night_discount:=t.night_discount_percent; end if;
 total:=round(t.price_per_hour*billable/60*(100-discount)/100*(100-night_discount)/100,2);
 return jsonb_build_object('billable_minutes',billable,'discount_percent',discount,'night_discount_percent',night_discount,'quoted_total',total);
end $$;
revoke all on function public.quote_booking(bigint,bigint,bigint,timestamptz,timestamptz) from public,anon;
grant execute on function public.quote_booking(bigint,bigint,bigint,timestamptz,timestamptz) to authenticated;

create function private.booking_rules() returns trigger language plpgsql set search_path='' as $$
declare q jsonb; recalculate boolean:=tg_op='INSERT'; role_name text:=private.current_role();
begin
 if tg_op='UPDATE' then recalculate:=(new.customer_id,new.station_id,new.tariff_id,new.starts_at,new.ends_at) is distinct from (old.customer_id,old.station_id,old.tariff_id,old.starts_at,old.ends_at); end if;
 if role_name='client' then
  if new.customer_id is distinct from private.customer_id() or new.status not in ('reserved','cancelled') or new.starts_at<=now() then
   raise sqlstate 'PT422' using message='Бронь недоступна для изменения',detail='{"starts_at":"Клиент изменяет только свои будущие бронирования"}'; end if;
  if tg_op='UPDATE' and (old.status not in ('reserved','cancelled') or old.starts_at<=now()) then raise insufficient_privilege using message='Сеанс уже начался'; end if;
 end if;
 if recalculate then
  if tg_op='UPDATE' and exists(select 1 from public.sessions where booking_id=old.id and deleted_at is null) then raise sqlstate 'PT409' using message='У бронирования уже есть сеанс'; end if;
  q:=public.quote_booking(new.customer_id,new.station_id,new.tariff_id,new.starts_at,new.ends_at);
  new.quoted_total:=(q->>'quoted_total')::numeric; new.billable_minutes:=(q->>'billable_minutes')::int;
  new.discount_percent:=(q->>'discount_percent')::int; new.night_discount_percent:=(q->>'night_discount_percent')::int;
 else
  new.quoted_total:=old.quoted_total; new.billable_minutes:=old.billable_minutes;
  new.discount_percent:=old.discount_percent; new.night_discount_percent:=old.night_discount_percent;
 end if;
 return new;
end $$;

create function private.session_rules() returns trigger language plpgsql set search_path='' as $$
declare b public.bookings; t public.tariffs; mins int;
begin
 select * into b from public.bookings where id=new.booking_id and deleted_at is null for update;
 if b.id is null or b.status='cancelled' then raise sqlstate 'PT422' using message='Бронь недоступна',detail='{"booking_id":"Выберите действующее бронирование"}'; end if;
 if tg_op='UPDATE' and new.booking_id<>old.booking_id then raise sqlstate 'PT422' using message='Бронь сеанса неизменна',detail='{"booking_id":"Создайте другой сеанс"}'; end if;
 if new.finished_at is not null and (new.finished_at<=new.started_at or new.finished_at>new.started_at+interval '24 hours') then
  raise sqlstate 'PT422' using message='Неверная длительность',detail='{"finished_at":"Окончание позже начала, длительность до 24 часов"}'; end if;
 if new.started_at>b.ends_at or new.started_at<b.starts_at-interval '15 minutes' then
  raise sqlstate 'PT422' using message='Неверное начало',detail='{"started_at":"Начало в интервале брони, допустимо на 15 минут раньше"}'; end if;
 if exists(select 1 from public.sessions x join public.bookings y on y.id=x.booking_id where y.station_id=b.station_id and x.id<>coalesce(new.id,0)
  and x.finished_at is null and x.deleted_at is null and new.deleted_at is null and new.finished_at is null) then raise sqlstate 'PT409' using message='На компьютере уже идёт другой сеанс'; end if;
 if tg_op='INSERT' then new.operator_id:=auth.uid(); else new.operator_id:=old.operator_id; end if;
 select * into t from public.tariffs where id=b.tariff_id;
 new.actual_minutes:=case when new.finished_at is null then 0 else ceil(extract(epoch from new.finished_at-new.started_at)/60) end;
 mins:=ceil(greatest(new.actual_minutes,t.min_minutes)::numeric/t.step_minutes)*t.step_minutes;
 new.charge:=case when new.finished_at is null then 0 else round(t.price_per_hour*mins/60*(100-b.discount_percent)/100*(100-b.night_discount_percent)/100,2) end;
 return new;
end $$;
create function private.session_status() returns trigger language plpgsql set search_path='' as $$
declare bid bigint;
begin
 bid:=case when tg_op='DELETE' then old.booking_id else new.booking_id end;
 update public.bookings set status=case
  when exists(select 1 from public.sessions where booking_id=bid and deleted_at is null and finished_at is null) then 'checked_in'
  when exists(select 1 from public.sessions where booking_id=bid and deleted_at is null) then 'completed' else 'reserved' end where id=bid;
 return null;
end $$;
create function private.payment_rules() returns trigger language plpgsql set search_path='' as $$
begin
 if tg_op='INSERT' then new.operator_id:=auth.uid(); else new.operator_id:=old.operator_id; end if;
 return new;
end $$;
create function private.profile_rules() returns trigger language plpgsql set search_path='' as $$
begin
 if tg_op='UPDATE' and (new.id<>old.id or new.created_at<>old.created_at) then raise insufficient_privilege; end if;
 if old.role='admin' and old.active and old.deleted_at is null and (new.role<>'admin' or not new.active or new.deleted_at is not null)
 and not exists(select 1 from public.profiles where role='admin' and active and deleted_at is null and id<>old.id) then
  raise sqlstate 'PT409' using message='Нельзя отключить последнего администратора'; end if;
 return new;
end $$;

create function private.signup_profile() returns trigger language plpgsql security definer set search_path='' as $$
begin
 insert into public.profiles(id,full_name,role) values(new.id,left(coalesce(nullif(btrim(new.raw_user_meta_data->>'full_name'),''),'Новый клиент'),100),'client');
 insert into public.customers(profile_id,full_name,email,phone,birth_year,category)
 values(new.id,left(coalesce(nullif(btrim(new.raw_user_meta_data->>'full_name'),''),'Новый клиент'),100),new.email,'+70000000000',2000,'guest');
 return new;
end $$;
