create function public.bulk_records(p_table text,p_ids bigint[],p_action text) returns int language plpgsql security invoker set search_path='' as $$
declare n int;
begin
 if p_table not in ('customers','zones','stations','games','station_games','tariffs','memberships','bookings','sessions','payments') or p_action not in ('soft','restore','hard') then raise invalid_parameter_value; end if;
 if cardinality(p_ids)>100 or cardinality(p_ids)<1 then raise sqlstate 'PT422' using message='Выберите от 1 до 100 записей'; end if;
 if p_action='hard' then execute format('delete from public.%I where id=any($1)',p_table) using p_ids;
 else execute format('update public.%I set deleted_at=%s where id=any($1)',p_table,case when p_action='restore' then 'null' else 'now()' end) using p_ids; end if;
 get diagnostics n=row_count;
 if n<>cardinality(p_ids) then raise insufficient_privilege using message='Не все записи доступны для этой операции'; end if;
 return n;
exception when exclusion_violation then raise sqlstate 'PT409' using message='На выбранное время уже существует бронирование';
end $$;
create function public.set_station_games(p_station_id bigint,p_game_ids bigint[]) returns void language plpgsql security invoker set search_path='' as $$
begin
 if private.current_role()<>'admin' then raise insufficient_privilege; end if;
 perform 1 from public.stations where id=p_station_id and deleted_at is null for update;
 if not found then raise no_data_found; end if;
 update public.station_games set deleted_at=now() where station_id=p_station_id and not (game_id=any(p_game_ids));
 insert into public.station_games(station_id,game_id,version,installed_at,enabled)
 select p_station_id,g,'1.0',current_date,true from unnest(p_game_ids) g
 on conflict(station_id,game_id) do update set deleted_at=null,enabled=true;
end $$;
revoke all on function public.bulk_records(text,bigint[],text),public.set_station_games(bigint,bigint[]) from public,anon;
grant execute on function public.bulk_records(text,bigint[],text),public.set_station_games(bigint,bigint[]) to authenticated;

create function public.save_booking(p_id bigint,p_data jsonb) returns jsonb language plpgsql security invoker set search_path='' as $$
declare result public.bookings;
begin
 if p_id is null then
  insert into public.bookings(customer_id,station_id,tariff_id,starts_at,ends_at,status,comment)
  values((p_data->>'customer_id')::bigint,(p_data->>'station_id')::bigint,(p_data->>'tariff_id')::bigint,
   (p_data->>'starts_at')::timestamptz,(p_data->>'ends_at')::timestamptz,coalesce(p_data->>'status','reserved'),p_data->>'comment') returning * into result;
 else
  update public.bookings set customer_id=(p_data->>'customer_id')::bigint,station_id=(p_data->>'station_id')::bigint,
   tariff_id=(p_data->>'tariff_id')::bigint,starts_at=(p_data->>'starts_at')::timestamptz,ends_at=(p_data->>'ends_at')::timestamptz,
   status=p_data->>'status',comment=p_data->>'comment' where id=p_id returning * into result;
  if not found then raise insufficient_privilege using message='Бронирование недоступно'; end if;
 end if;
 return to_jsonb(result);
exception when exclusion_violation then raise sqlstate 'PT409' using message='Компьютер уже занят в это время. Выберите другой интервал.';
end $$;
-- Availability returns only occupied intervals, never another client's identity.
create function private.busy_intervals(p_from timestamptz,p_to timestamptz) returns jsonb language plpgsql stable security definer set search_path='' as $$
begin
 if private.current_role() is null then raise insufficient_privilege; end if;
 if p_from is null or p_to is null or p_to<=p_from or p_to-p_from>interval '7 days' then raise sqlstate 'PT422' using message='Выберите интервал до 7 дней'; end if;
 return coalesce((select jsonb_agg(jsonb_build_object('station_id',station_id,'starts_at',starts_at,'ends_at',ends_at)) from public.bookings
  where deleted_at is null and status<>'cancelled' and starts_at<p_to and ends_at>p_from),'[]'::jsonb);
end $$;
create function public.availability(p_from timestamptz,p_to timestamptz) returns jsonb language sql stable security invoker set search_path='' as $$
 select private.busy_intervals(p_from,p_to)
$$;
revoke all on function public.save_booking(bigint,jsonb),public.availability(timestamptz,timestamptz),private.busy_intervals(timestamptz,timestamptz) from public,anon;
grant execute on function public.save_booking(bigint,jsonb),public.availability(timestamptz,timestamptz),private.busy_intervals(timestamptz,timestamptz) to authenticated;
notify pgrst,'reload schema';
commit;
